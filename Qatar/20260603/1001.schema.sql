CREATE   OR ALTER    PROCEDURE [QATALUM].[P_MERGE_ACTION_REFERENCE]
     @TRANS INT
	 ,@ACTION_NO int
    ,@REFERENCE INT 
    ,@INT_VALUE bigint  = 0
    ,@FLOAT_VALUE FLOAT  = 0
    ,@STRING_VALUE nvarchar(2000) = ''
	,@DATE_VALUE DATETIME = NULL
    ,@REFERENCE_OPTION INT  = 0

AS
BEGIN 


   DECLARE @REFERENCE_TYPE INT
   DECLARE @NEXT_REFERENCE_NO INT
   IF @DATE_VALUE IS NULL
   BEGIN
     SET @DATE_VALUE = GETDATE()
   END 

   SELECT  @REFERENCE_TYPE = REFERENCE_TYPE FROM QATALUM.C_REFERENCE  WITH (NOLOCK) WHERE REFERENCE = @REFERENCE

   SELECT @NEXT_REFERENCE_NO = ISNULL( MAX(REFERENCE_NO),0) +1 FROM QATALUM.D_ACTION_REFERENCE   WITH(NOLOCK) WHERE TRANS = @TRANS AND ACTION_NO=@ACTION_NO

   --TEXT
   IF ( @REFERENCE_TYPE = 1 )
     BEGIN
        IF EXISTS(select 1 from QATALUM.D_ACTION_REFERENCE  WITH (NOLOCK) WHERE REFERENCE = @REFERENCE AND TRANS=@TRANS AND ACTION_NO=@ACTION_NO )  
            BEGIN
              UPDATE QATALUM.D_ACTION_REFERENCE SET VALUE = @STRING_VALUE
              WHERE  REFERENCE = @REFERENCE AND TRANS=@TRANS AND ACTION_NO=@ACTION_NO 
            END
        ELSE  
            BEGIN                   
                INSERT INTO QATALUM.D_ACTION_REFERENCE (TRANS,REFERENCE_NO,REFERENCE, VALUE, REFERENCE_OPTION, ACTION_NO)
                VALUES(@TRANS,@NEXT_REFERENCE_NO,   @REFERENCE,@STRING_VALUE,0,@ACTION_NO)
            END   
     END
    -- DATE
   ELSE IF ( @REFERENCE_TYPE = 6 OR  @REFERENCE_TYPE = 10 )
     BEGIN
        IF EXISTS(select 1 from QATALUM.D_ACTION_REFERENCE  WITH (NOLOCK) WHERE REFERENCE = @REFERENCE AND TRANS=@TRANS AND ACTION_NO=@ACTION_NO )  
            BEGIN
              UPDATE QATALUM.D_ACTION_REFERENCE SET VALUE_DATE = @DATE_VALUE
              WHERE  REFERENCE = @REFERENCE AND TRANS=@TRANS AND ACTION_NO=@ACTION_NO 
            END
        ELSE  
            BEGIN                   
                INSERT INTO QATALUM.D_ACTION_REFERENCE (TRANS,REFERENCE_NO,REFERENCE, VALUE_DATE, REFERENCE_OPTION,ACTION_NO)
                VALUES(@TRANS,@NEXT_REFERENCE_NO,   @REFERENCE,@DATE_VALUE,0,@ACTION_NO)
            END   
     END
     -- FLOAT
    ELSE IF ( @REFERENCE_TYPE = 8  OR @FLOAT_VALUE > 0)
     BEGIN
        IF EXISTS(select 1 from QATALUM.D_ACTION_REFERENCE  WITH (NOLOCK) WHERE REFERENCE = @REFERENCE AND TRANS=@TRANS AND ACTION_NO=@ACTION_NO)  
            BEGIN
              UPDATE QATALUM.D_ACTION_REFERENCE SET VALUE_FLOAT = @FLOAT_VALUE
              WHERE  REFERENCE = @REFERENCE AND TRANS=@TRANS AND ACTION_NO=@ACTION_NO
            END
        ELSE  
            BEGIN                   
                INSERT INTO QATALUM.D_ACTION_REFERENCE (TRANS,REFERENCE_NO,REFERENCE, VALUE_FLOAT, REFERENCE_OPTION,ACTION_NO)
                VALUES(@TRANS,@NEXT_REFERENCE_NO,   @REFERENCE,@FLOAT_VALUE,0,@ACTION_NO)
            END   
     END  
     -- INT
    ELSE IF ( @REFERENCE_TYPE = 7 )
     BEGIN
        IF EXISTS(select 1 from QATALUM.D_ACTION_REFERENCE WITH (NOLOCK)  WHERE REFERENCE = @REFERENCE AND TRANS=@TRANS AND ACTION_NO=@ACTION_NO)  
            BEGIN
              UPDATE QATALUM.D_ACTION_REFERENCE SET VALUE_INTEGER = @INT_VALUE
              WHERE  REFERENCE = @REFERENCE AND TRANS=@TRANS AND ACTION_NO=@ACTION_NO
            END
        ELSE  
            BEGIN                   
                INSERT INTO QATALUM.D_ACTION_REFERENCE (TRANS,REFERENCE_NO,REFERENCE, VALUE_INTEGER, REFERENCE_OPTION,ACTION_NO)
                VALUES(@TRANS,@NEXT_REFERENCE_NO,   @REFERENCE,@INT_VALUE,0,@ACTION_NO)
            END   
     END  
     --  SINGLE SELECTION,  MULTI SELECTION
    ELSE IF ( @REFERENCE_TYPE = 4 OR @REFERENCE_TYPE = 5 OR @REFERENCE_TYPE = 9) AND @REFERENCE_OPTION IS NOT NULL
     BEGIN

        IF EXISTS(select 1 from QATALUM.D_ACTION_REFERENCE  WITH (NOLOCK) WHERE REFERENCE = @REFERENCE AND TRANS=@TRANS AND ACTION_NO=@ACTION_NO)  
            BEGIN
              UPDATE QATALUM.D_ACTION_REFERENCE SET REFERENCE_OPTION = @REFERENCE_OPTION
              WHERE  REFERENCE = @REFERENCE AND TRANS=@TRANS AND ACTION_NO=@ACTION_NO
            END
        ELSE  
            BEGIN                   
                INSERT INTO QATALUM.D_ACTION_REFERENCE (TRANS,REFERENCE_NO,REFERENCE,  REFERENCE_OPTION, ACTION_NO)
                VALUES(@TRANS,@NEXT_REFERENCE_NO,   @REFERENCE,@REFERENCE_OPTION,@ACTION_NO)
            END  
     END  
    

END
GO
PRINT N'Creating Procedure [QATALUM].[P_ACTION_POST_SAVE]...';


GO


