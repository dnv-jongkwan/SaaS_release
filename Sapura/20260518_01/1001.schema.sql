CREATE          FUNCTION [synergix].[GET_EMAIL_TEXT] (@PERSON int, @DOMAIN_BLOB int, @TEXT int)
RETURNS NVARCHAR(4000)
AS
BEGIN
      DECLARE @RET_TEXT NVARCHAR(4000), @DEFAULT_LANG int

	  SELECT TOP 1 @DEFAULT_LANG = LANGUAGE FROM SYNERGIX.P_PERSON WITH(NOLOCK) WHERE PERSON =@PERSON
	  SET @DEFAULT_LANG = ISNULL(@DEFAULT_LANG,2)

	  SELECT TOP 1 @RET_TEXT = DESCRIPTION FROM SYNERGIX.X_TEXT WITH(NOLOCK) WHERE DOMAIN_BLOB = @DOMAIN_BLOB AND TEXT =@TEXT AND LANGUAGE= @DEFAULT_LANG
	  
	  RETURN ISNULL(@RET_TEXT,N'')


END
