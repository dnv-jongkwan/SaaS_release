create   function [synergix].[GET_VALID_TRANS](@TRANS INT) RETURNS INT
AS
BEGIN
   DECLARE @TRANS_ID int
   DECLARE @RET_TRANS int =0
   SELECT @TRANS_ID = TRANS_ID FROM SYNERGIX.D_TRANS  WITH(NOLOCK) WHERE TRANS = @TRANS

   select  @RET_TRANS= V1.TRANS
   from SYNERGIX.D_TRANS T1 WITH(NOLOCK) 
     INNER JOIN SYNERGIX.D_TRANS_VALID V1 WITH(NOLOCK) 
	   ON T1.TRANS = V1.TRANS
	WHERE T1.TRANS_ID = @TRANS_ID

   RETURN @RET_TRANS
END
