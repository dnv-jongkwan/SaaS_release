CREATE   function [synergix].[EXIST_SYNERGI_REFERENCE_OPTION](@TRANS INT, @REFERENCE INT, @REFERENCE_OPTION INT) RETURNS INT
AS

BEGIN
   DECLARE @RET INT =0
   SELECT @RET =
      CASE WHEN EXISTS (SELECT 1 FROM SYNERGIX.D_SYNERGI_REFERENCE  WITH(NOLOCK) WHERE TRANS = @TRANS AND REFERENCE = @REFERENCE
              AND REFERENCE_OPTION = @REFERENCE_OPTION) THEN 1
		   ELSE 0
	  END

   return @RET;
END
