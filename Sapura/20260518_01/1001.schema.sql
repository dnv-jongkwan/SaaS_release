CREATE          FUNCTION [synergix].[IS_REFERENCE_CHANGED_DOUBLE] (@TRANS int, @OPT_REFERENCES int, @INT_REFERENCE int)
RETURNS int
AS
BEGIN

	  IF   EXISTS(SELECT 1 FROM SYNERGIX.D_SYNERGI_REFERENCE R20794 WITH(NOLOCK) 
		                   WHERE R20794.TRANS =@TRANS  
						   AND R20794.REFERENCE = @OPT_REFERENCES
	                       AND  NOT EXISTS(SELECT 1 FROM  SYNERGIX.D_SYNERGI_REFERENCE R20796 WITH(NOLOCK)
						                  WHERE  R20794.TRANS =R20796.TRANS
										  AND  R20796.REFERENCE = @INT_REFERENCE
										  AND  R20794.REFERENCE_OPTION = R20796.VALUE_INTEGER))
	   BEGIN
	      RETURN 1
	   END
	   RETURN 0


