CREATE   PROCEDURE [synergix].[EXT_MERGE_SYNERGI_REFERENCE]
     @TRANS INT
    ,@REFERENCE INT 
    ,@INT_VALUE BIGINT  = 0
    ,@FLOAT_VALUE FLOAT  = 0
    ,@STRING_VALUE NVARCHAR(2000) = N''
    ,@DATE_VALUE DATETIME = NULL
    ,@REFERENCE_OPTION INT  = 0
AS
BEGIN
    SET NOCOUNT ON;

    IF NOT EXISTS (SELECT 1 FROM SYNERGIX.D_TRANS WITH (NOLOCK) WHERE TRANS = @TRANS)
        RETURN;

    IF @DATE_VALUE IS NULL SET @DATE_VALUE = GETDATE();

    DECLARE @REFERENCE_TYPE INT;

    SELECT @REFERENCE_TYPE = REFERENCE_TYPE
    FROM SYNERGIX.C_REFERENCE WITH (NOLOCK)
    WHERE REFERENCE = @REFERENCE;

    IF @REFERENCE_TYPE = 8 AND @FLOAT_VALUE = 0 AND @STRING_VALUE <> N''
        SET @FLOAT_VALUE = TRY_CAST(@STRING_VALUE AS FLOAT);

    IF @REFERENCE_TYPE = 7 AND @INT_VALUE = 0 AND @STRING_VALUE <> N''
        SET @INT_VALUE = TRY_CAST(@STRING_VALUE AS BIGINT);

    -- 1) UPDATE 먼저
    UPDATE t
       SET VALUE           = CASE WHEN @REFERENCE_TYPE = 1 THEN @STRING_VALUE ELSE t.VALUE END,
           VALUE_DATE      = CASE WHEN @REFERENCE_TYPE IN (6,10) THEN @DATE_VALUE ELSE t.VALUE_DATE END,
           VALUE_FLOAT     = CASE WHEN @REFERENCE_TYPE = 8 THEN @FLOAT_VALUE ELSE t.VALUE_FLOAT END,
           VALUE_INTEGER   = CASE WHEN @REFERENCE_TYPE = 7 THEN @INT_VALUE ELSE t.VALUE_INTEGER END,
           REFERENCE_OPTION= CASE WHEN @REFERENCE_TYPE IN (4,5,9) THEN @REFERENCE_OPTION ELSE t.REFERENCE_OPTION END
    FROM SYNERGIX.D_SYNERGI_REFERENCE t
    WHERE t.TRANS = @TRANS
      AND t.REFERENCE = @REFERENCE;

    IF @@ROWCOUNT > 0
        RETURN;

    -- 2) 없으면 INSERT 시도 (경쟁 대비 TRY/CATCH)
    DECLARE @refno INT;

    BEGIN TRY
        SELECT @refno = ISNULL(MAX(REFERENCE_NO), 0) + 1
        FROM SYNERGIX.D_SYNERGI_REFERENCE WITH (UPDLOCK, HOLDLOCK)
        WHERE TRANS = @TRANS;

        INSERT INTO SYNERGIX.D_SYNERGI_REFERENCE
            (TRANS, REFERENCE_NO, REFERENCE, VALUE, VALUE_DATE, VALUE_FLOAT, VALUE_INTEGER, REFERENCE_OPTION)
        VALUES
            (@TRANS, @refno, @REFERENCE,
             CASE WHEN @REFERENCE_TYPE = 1 THEN @STRING_VALUE ELSE NULL END,
             CASE WHEN @REFERENCE_TYPE IN (6,10) THEN @DATE_VALUE ELSE NULL END,
             CASE WHEN @REFERENCE_TYPE = 8 THEN @FLOAT_VALUE ELSE NULL END,
             CASE WHEN @REFERENCE_TYPE = 7 THEN @INT_VALUE ELSE NULL END,
             CASE WHEN @REFERENCE_TYPE IN (4,5,9) THEN @REFERENCE_OPTION ELSE 0 END);
    END TRY
    BEGIN CATCH
        PRINT('INSERT ERROR  OF D_SYNERGI_REFERENCE')
    END CATCH
END
